// Beautiful water drop chime synthesis using Web Audio API
function playWaterChime() {
  const AudioContext = window.AudioContext || window.webkitAudioContext;
  if (!AudioContext) return;
  const ctx = new AudioContext();
  
  // Oscillator 1: Droplet body (bubble frequency sweep)
  const osc1 = ctx.createOscillator();
  const gain1 = ctx.createGain();
  osc1.type = 'sine';
  osc1.frequency.setValueAtTime(450, ctx.currentTime);
  osc1.frequency.exponentialRampToValueAtTime(1300, ctx.currentTime + 0.07);
  
  gain1.gain.setValueAtTime(0.001, ctx.currentTime);
  gain1.gain.linearRampToValueAtTime(0.3, ctx.currentTime + 0.005);
  gain1.gain.exponentialRampToValueAtTime(0.001, ctx.currentTime + 0.12);
  
  // Oscillator 2: High crystal chime overlay
  const osc2 = ctx.createOscillator();
  const gain2 = ctx.createGain();
  osc2.type = 'sine';
  osc2.frequency.setValueAtTime(2600, ctx.currentTime);
  osc2.frequency.exponentialRampToValueAtTime(2550, ctx.currentTime + 0.4);
  
  gain2.gain.setValueAtTime(0.001, ctx.currentTime);
  gain2.gain.linearRampToValueAtTime(0.08, ctx.currentTime + 0.015);
  gain2.gain.exponentialRampToValueAtTime(0.001, ctx.currentTime + 0.45);
  
  // Connections
  osc1.connect(gain1);
  gain1.connect(ctx.destination);
  osc2.connect(gain2);
  gain2.connect(ctx.destination);
  
  // Start & Stop
  osc1.start(ctx.currentTime);
  osc1.stop(ctx.currentTime + 0.15);
  osc2.start(ctx.currentTime);
  osc2.stop(ctx.currentTime + 0.5);
}

// Dynamic Canvas-based background removal (BFS flood fill)
function processCharacterOnTheFly() {
  const charImg = document.getElementById('char-img');
  if (!charImg) return;

  const img = new Image();
  // Load the raw JPEG generated by the AI
  img.src = '../assets/character_raw.jpg';

  img.onload = () => {
    const canvas = document.createElement('canvas');
    const ctx = canvas.getContext('2d');
    const width = img.width;
    const height = img.height;

    canvas.width = width;
    canvas.height = height;
    ctx.drawImage(img, 0, 0);

    const imgData = ctx.getImageData(0, 0, width, height);
    const data = imgData.data;

    // Queue for BFS flood fill starting from boundaries
    const queue = [];
    const visited = new Uint8Array(width * height);

    // Enqueue boundary pixels
    for (let x = 0; x < width; x++) {
      queue.push([x, 0]);
      queue.push([x, height - 1]);
      visited[0 * width + x] = 1;
      visited[(height - 1) * width + x] = 1;
    }
    for (let y = 1; y < height - 1; y++) {
      queue.push([0, y]);
      queue.push([width - 1, y]);
      visited[y * width + 0] = 1;
      visited[y * width + (width - 1)] = 1;
    }

    // Colors near white (R>235, G>235, B>235) will be treated as background
    const threshold = 30;
    function isNearWhite(r, g, b) {
      return (255 - r) < threshold && (255 - g) < threshold && (255 - b) < threshold;
    }

    let head = 0;
    while (head < queue.length) {
      const [cx, cy] = queue[head++];
      const idx = (cy * width + cx) * 4;
      const r = data[idx];
      const g = data[idx + 1];
      const b = data[idx + 2];

      if (isNearWhite(r, g, b)) {
        // Enqueue neighbors (4-way)
        const neighbors = [
          [cx + 1, cy],
          [cx - 1, cy],
          [cx, cy + 1],
          [cx, cy - 1]
        ];

        for (const [nx, ny] of neighbors) {
          if (nx >= 0 && nx < width && ny >= 0 && ny < height) {
            const nVisitedIdx = ny * width + nx;
            if (!visited[nVisitedIdx]) {
              visited[nVisitedIdx] = 1;
              queue.push([nx, ny]);
            }
          }
        }
      }
    }

    // Apply transparency to visited background pixels and soften edges
    for (let y = 0; y < height; y++) {
      for (let x = 0; x < width; x++) {
        const idx = (y * width + x) * 4;
        const vIdx = y * width + x;

        if (visited[vIdx]) {
          const r = data[idx];
          const g = data[idx + 1];
          const b = data[idx + 2];
          if (isNearWhite(r, g, b)) {
            data[idx + 3] = 0; // Fully transparent
          }
        } else {
          // Detect edges for soft blending
          let isEdge = false;
          if (x > 0 && visited[y * width + (x - 1)]) isEdge = true;
          else if (x < width - 1 && visited[y * width + (x + 1)]) isEdge = true;
          else if (y > 0 && visited[(y - 1) * width + x]) isEdge = true;
          else if (y < height - 1 && visited[(y + 1) * width + x]) isEdge = true;

          if (isEdge) {
            const r = data[idx];
            const g = data[idx + 1];
            const b = data[idx + 2];
            const whiteDist = Math.max(255 - r, 255 - g, 255 - b);
            if (whiteDist < 45) {
              data[idx + 3] = Math.min(255, Math.max(0, Math.floor(whiteDist * 5.6)));
            }
          }
        }
      }
    }

    ctx.putImageData(imgData, 0, 0);
    // Replace raw image with transparent base64 data URL
    charImg.src = canvas.toDataURL('image/png');
  };
}

document.addEventListener('DOMContentLoaded', () => {
  const container = document.getElementById('popup-container');
  const speechBubble = document.getElementById('speech-bubble');
  const reminderMsg = document.getElementById('reminder-msg');
  const btnDrink = document.getElementById('btn-drink');
  const btnSnooze = document.getElementById('btn-snooze');
  const btnClose = document.getElementById('btn-close');

  // Process the raw character image to remove the background
  processCharacterOnTheFly();

  // Select random encouraging quotes
  const randomSpeech = speechQuotes[Math.floor(Math.random() * speechQuotes.length)];
  const randomMessage = messageQuotes[Math.floor(Math.random() * messageQuotes.length)];

  speechBubble.textContent = randomSpeech;
  reminderMsg.textContent = randomMessage;

  // Request audio settings from main process
  ipcRenderer.send('get-audio-settings');

  ipcRenderer.once('audio-settings-response', (event, { muteSound }) => {
    if (!muteSound) {
      playWaterChime();
    }
  });

  // Slide-in animation trigger
  setTimeout(() => {
    container.classList.add('active');
    setTimeout(() => {
      speechBubble.classList.add('active');
    }, 300);
  }, 100);

  // Close animation helper
  function triggerClose(action) {
    speechBubble.classList.remove('active');
    container.classList.add('closing');
    
    // Wait for slideDown animation (400ms) to complete before telling main process to close
    setTimeout(() => {
      ipcRenderer.send('action-complete', action);
    }, 400);
  }

  // Event Listeners
  btnDrink.addEventListener('click', () => {
    ipcRenderer.send('increment-water', 250); // Add 250ml
    triggerClose('drink');
  });

  btnSnooze.addEventListener('click', () => {
    ipcRenderer.send('snooze-reminder', 10); // Snooze for 10 minutes
    triggerClose('snooze');
  });

  btnClose.addEventListener('click', () => {
    triggerClose('dismiss');
  });
});
